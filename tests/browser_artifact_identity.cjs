const {expect}=require(process.env.EKF_PLAYWRIGHT||'@playwright/test');
const {spawnSync}=require('node:child_process');
const assert=require('node:assert/strict');

module.exports=async({page,context,base,repo})=>{
  const get=async path=>(await context.request.get(base+'/api/'+path)).json();
  const snapshot=await get('snapshot');
  const ids=new Set(snapshot.artifacts.map(a=>a.id));
  const artifact=async id=>get('artifact?id='+encodeURIComponent(id));
  const parentId='REQ-SAFE-001',sourceId='INT-SYS-001';
  await page.locator('.nav-item[data-page="overview"]').click();
  await page.locator('#overview-root-type').selectOption('');
  await page.locator('#overview-root').selectOption(parentId);
  await page.locator(`.graph-node[data-artifact="${parentId}"]`).click({button:'right'});
  await page.getByRole('menuitem',{name:'Create child…',exact:true}).click();
  await expect(page.locator('select#edit-type')).toHaveValue('requirement');
  await expect(page.locator('select#edit-discipline')).toHaveValue('Systems');
  await expect(page.locator('#edit-type option[value="verification"]')).toHaveCount(1);
  await expect(page.locator('#edit-type option[value="manufacturing-requirement"]')).toHaveCount(1);
  await expect(page.locator('#edit-discipline option[value="Integration"]')).toHaveCount(1);
  await expect(page.locator('#edit-id')).toHaveValue(/^REQ-\d{3,}$/);
  assert.ok(!ids.has(await page.locator('#edit-id').inputValue()));
  await page.locator('#edit-type').selectOption('component');
  await expect(page.locator('#edit-id')).toHaveValue(/^CMP-\d{3,}$/);
  await page.locator('#edit-type').selectOption({label:'Add custom type…'});
  await expect(page.locator('#edit-type-custom')).toBeVisible();
  await page.locator('#edit-type-custom').fill('load-case');
  await expect(page.locator('#edit-id')).toHaveValue('LOAD-CASE-001');
  await page.locator('#edit-discipline').selectOption({label:'Add custom discipline…'});
  await page.locator('#edit-discipline-custom').fill('Integration & Test');
  await page.locator('#edit-title').fill('A child with a type-based ID');
  await page.getByRole('button',{name:'Markdown source',exact:true}).click();
  await page.locator('#edit-body').fill('Preserve this meaning while IDs and selections change.');
  await page.locator('#child-link-direction').selectOption('parent-child');
  await page.locator('#child-relationship').fill('verified-by');
  await page.locator('[data-action="editor-links"][data-direction="incoming"]').click();
  await page.locator('#link-query').fill(sourceId);
  await page.locator(`[data-link-select="${sourceId}"]`).check();
  await page.locator('[data-link-action="stage"]').click();
  await page.locator('[data-link-action="save"]').click();
  await expect(page.locator('#edit-id')).toHaveAttribute('readonly','');
  await page.locator('#edit-type').selectOption('verification');
  const childId=await page.locator('#edit-id').inputValue();
  assert.match(childId,/^VER-\d{3,}$/);
  assert.ok(!ids.has(childId));
  await expect(page.locator('#child-link-preview')).toHaveText(`${parentId} → verified-by → ${childId}`);
  await page.locator('[data-action="editor-links"][data-manage="true"]').click();
  await expect(page.locator('#link-existing')).toContainText(childId);
  await expect(page.locator('#link-existing')).not.toContainText('LOAD-CASE-001');
  await page.keyboard.press('Escape');
  await expect(page.locator('#edit-body')).toHaveValue('Preserve this meaning while IDs and selections change.');
  const before=(await get('snapshot')).head;
  await page.getByRole('button',{name:'Create child',exact:true}).click();
  await expect(page.locator('.drawer-head h2')).toHaveText('A child with a type-based ID');
  const child=await artifact(childId);
  assert.equal(child.type,'verification');
  assert.equal(child.meta.discipline,'Integration & Test');
  assert.ok((await artifact(parentId)).meta.relations.some(r=>r.type==='verified-by'&&r.target===childId));
  assert.ok((await artifact(sourceId)).meta.relations.some(r=>r.type==='depends-on'&&r.target===childId));
  assert.ok(!(await get('snapshot')).edges.some(r=>r.target==='LOAD-CASE-001'));
  assert.equal(spawnSync('git',['-C',repo,'rev-list','--count',before+'..HEAD'],{encoding:'utf8'}).stdout.trim(),'1');

  // Reclassifying an existing concept never renames its stable ID or breaks incoming links.
  await page.locator('.drawer-head [data-action="edit"]').click();
  await expect(page.locator('#edit-id')).toHaveAttribute('readonly','');
  await expect(page.locator('#edit-discipline')).toHaveValue('Integration & Test');
  await page.locator('#edit-type').selectOption('component');
  await page.locator('#edit-discipline').selectOption('Software');
  await expect(page.locator('#edit-id')).toHaveValue(childId);
  await expect(page.locator('#edit-id-help')).toContainText('Saved IDs stay fixed');
  await page.getByRole('button',{name:'Save artifact',exact:true}).click();
  await expect(page.locator('.drawer-head h2')).toHaveText(child.title);
  assert.equal((await artifact(childId)).type,'component');
  assert.ok((await artifact(sourceId)).meta.relations.some(r=>r.target===childId));
  await page.keyboard.press('Escape');

  await page.locator('.nav-item[data-page="knowledge"]').click();
  await page.getByRole('button',{name:'New artifact',exact:true}).click();
  await page.locator('#edit-id').fill('MY-MANUAL-ID');
  await page.locator('#edit-type').selectOption('hazard');
  await expect(page.locator('#edit-id')).toHaveValue('MY-MANUAL-ID');
  await expect(page.locator('#edit-id-help')).toContainText('Custom ID kept');
  await page.getByRole('button',{name:'Suggest ID',exact:true}).click();
  await expect(page.locator('#edit-id')).toHaveValue(/^HAZ-\d{3,}$/);
  await page.locator('#edit-type').selectOption('requirement');
  await expect(page.locator('#edit-id')).toHaveValue(/^REQ-\d{3,}$/);

  // Another writer can claim a suggestion. Reject the collision; refresh only the ID, preserving the draft.
  const claimed=await page.locator('#edit-id').inputValue();
  const response=await context.request.post(base+'/api/artifact',{data:{path:'engineering/id-claimed-elsewhere.md',raw:`---\nekf: "0.1"\nid: ${claimed}\ntype: requirement\ntitle: An externally created artifact\n---\n\nKeep the external artifact.\n`}});
  assert.equal(response.status(),200,await response.text());
  await page.locator('#edit-title').fill('Preserved draft after an ID collision');
  await page.getByRole('button',{name:'Save artifact',exact:true}).click();
  await expect(page.locator('#form-error')).toContainText('ID is already used');
  await page.getByRole('button',{name:'Suggest ID',exact:true}).click();
  await expect(page.locator('#edit-id')).not.toHaveValue(claimed);
  const nextId=await page.locator('#edit-id').inputValue();
  await expect(page.locator('#edit-title')).toHaveValue('Preserved draft after an ID collision');
  await page.getByRole('button',{name:'Save artifact',exact:true}).click();
  await expect(page.locator('.drawer-head h2')).toHaveText('Preserved draft after an ID collision');
  assert.equal((await artifact(claimed)).title,'An externally created artifact');
  assert.equal((await artifact(nextId)).title,'Preserved draft after an ID collision');
  await page.keyboard.press('Escape');

  // Empty custom values fail visibly; custom choices are saved and reusable in later dropdowns.
  await page.getByRole('button',{name:'New artifact',exact:true}).click();
  await page.locator('#edit-type').selectOption({label:'Add custom type…'});
  await page.getByRole('button',{name:'Save artifact',exact:true}).click();
  await expect(page.locator('#form-error')).toContainText('enter a custom type');
  await page.locator('#edit-type-custom').fill('load-case');
  await page.locator('#edit-title').fill('Custom load case');
  await page.locator('#edit-discipline').selectOption({label:'Add custom discipline…'});
  await page.getByRole('button',{name:'Save artifact',exact:true}).click();
  await expect(page.locator('#form-error')).toContainText('Enter a custom discipline');
  await page.locator('#edit-discipline-custom').fill('Flight dynamics');
  const customId=await page.locator('#edit-id').inputValue();
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.locator('.modal').evaluate(el=>el.scrollWidth>el.clientWidth),false,'Dropdown editor overflow');
  await page.screenshot({path:'/tmp/ekf-artifact-dropdowns-mobile.png',animations:'disabled'});
  await page.getByRole('button',{name:'Save artifact',exact:true}).click();
  await expect(page.locator('.drawer-head h2')).toHaveText('Custom load case');
  assert.equal((await artifact(customId)).type,'load-case');
  assert.equal((await artifact(customId)).meta.discipline,'Flight dynamics');
  await page.keyboard.press('Escape');
  await page.setViewportSize({width:1440,height:1100});
  await page.getByRole('button',{name:'New artifact',exact:true}).click();
  await page.locator('#edit-type').selectOption('load-case');
  await expect(page.locator('#edit-id')).toHaveValue('LOAD-CASE-002');
  await page.locator('#edit-discipline').selectOption('Flight dynamics');
  await page.screenshot({path:'/tmp/ekf-artifact-dropdowns.png',animations:'disabled'});
  await page.keyboard.press('Escape');
  console.log('Artifact type/discipline dropdowns, custom choices, generated IDs, stable existing IDs, draft-link retargeting, collisions and mobile layout passed.');
};
