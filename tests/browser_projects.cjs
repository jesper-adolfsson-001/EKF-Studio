const {expect,request}=require(process.env.EKF_PLAYWRIGHT||'@playwright/test');
const {spawnSync}=require('node:child_process');
const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');

module.exports=async({page,context,base,temp,projectsFolder})=>{
  const get=async name=>(await context.request.get(base+'/api/'+name)).json();
  const projects=()=>page.locator('.nav-item[data-page="projects"]').click();
  const snapshot=()=>get('snapshot');
  const create=async title=>{
    await page.getByRole('button',{name:'New local project',exact:true}).click();
    await page.locator('#project-title').fill(title);
    await expect(page.locator('#project-folder')).toHaveValue(title);
    await page.getByRole('button',{name:'Create project',exact:true}).click();
    await expect(page.getByRole('heading',{name:'Engineering, connected.',exact:true})).toBeVisible();
    return (await get('projects')).selected;
  };
  const open=async id=>{await projects();await page.locator(`[data-project-action="open"][data-id="${id}"]`).click();await expect(page.getByRole('heading',{name:'Engineering, connected.',exact:true})).toBeVisible();};
  const githubSetup=async()=>{await projects();await page.getByRole('button',{name:'GitHub setup',exact:true}).click();};
  await expect(page.getByRole('heading',{name:'Your projects',exact:true})).toBeVisible();
  assert.equal((await get('projects')).projects.length,0);
  const a=await create('GardenA');
  const aToken=fs.readFileSync(path.join(projectsFolder,'GardenA','.ekf/agent-token'),'utf8');
  await page.locator('.nav-item[data-page="knowledge"]').click();
  await page.getByRole('button',{name:'New artifact',exact:true}).first().click();
  await page.locator('#edit-id').fill('GARDEN-001');await page.locator('#edit-title').fill('Garden A draft');
  await page.getByRole('button',{name:'Save artifact',exact:true}).click();
  await expect(page.locator('.drawer-head h2')).toHaveText('Garden A draft');
  const draft=(await snapshot()).workflow.id,artifact=(await snapshot()).artifacts[0];
  await page.keyboard.press('Escape');await projects();const b=await create('GardenB');
  assert.equal((await snapshot()).artifacts.length,0);assert.equal((await snapshot()).workflow.id,null);
  const stale=await context.request.post(base+'/api/artifact',{data:{project:a,workspace:draft,path:artifact.path,raw:artifact.raw,expected_hash:artifact.hash}});
  assert.equal(stale.status(),409);assert.match((await stale.json()).error,/project changed/);
  const agent=await request.newContext({baseURL:base,extraHTTPHeaders:{Authorization:'Bearer '+aToken}});
  assert.equal((await agent.get('/api/snapshot')).status(),401);
  await open(a);assert.equal((await snapshot()).workflow.id,draft);
  assert.equal((await agent.get('/api/projects')).status(),403);
  assert.equal((await agent.post('/api/github/publish',{data:{}})).status(),403);
  // Baseline state is cleared when opening a different project.
  await context.request.post(base+'/api/baselines',{data:{name:'garden-draft'}});await page.reload();
  await page.locator('#workspace-revision').selectOption('garden-draft');await expect(page.locator('.baseline-banner')).toBeVisible();
  await open(b);await expect(page.locator('.baseline-banner')).toHaveCount(0);
  await open(a);
  await githubSetup();await expect(page.locator('.modal-head h2')).toHaveText('Connect your GitHub account');
  await page.getByRole('button',{name:'Sign in to GitHub',exact:true}).click();
  await expect(page.locator('.github-device-code')).toContainText('ABCD-1234');
  await expect(page.getByRole('link',{name:'Continue on GitHub'})).toHaveAttribute('href','https://github.com/login/device');
  await page.keyboard.press('Escape');await page.reload();
  await page.getByRole('button',{name:'View setup progress',exact:true}).click();
  await expect(page.locator('.github-device-code')).toContainText('ABCD-1234');
  fs.writeFileSync(path.join(projectsFolder,'.ekf/auth-complete'),'test browser approved');
  await expect(page.locator('.modal-head h2')).toHaveText('Connect this project');
  await page.getByRole('button',{name:'Publish as a new repository',exact:true}).click();
  await expect(page.locator('[name="github-visibility"][value="private"]')).toBeChecked();
  await page.locator('[name="github-visibility"][value="public"]').check();
  await expect(page.locator('#github-publish-summary')).toContainText('anyone to read');
  await expect(page.getByRole('button',{name:'Create public repository & upload',exact:true})).toBeVisible();
  await page.locator('[name="github-visibility"][value="private"]').check();
  await page.getByRole('button',{name:'Create private repository & upload',exact:true}).click();
  await expect(page.locator('.modal-head h2')).toHaveText('Project connected to GitHub');
  await expect(page.getByRole('link',{name:'Open repository on GitHub'})).toHaveAttribute('href','https://github.com/gardener/GardenA');
  const remote=path.join(temp,'remotes/gardener/GardenA.git');
  const refs=spawnSync('git',['-C',remote,'for-each-ref','--format=%(refname:short)'],{encoding:'utf8'});
  assert.equal(refs.status,0);assert.equal(refs.stdout.trim(),'main');
  assert.equal((await snapshot()).workflow.id,draft);
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'Open from GitHub',exact:true}).click();
  await page.locator('#github-filter').fill('GardenA');
  await page.locator('[data-project-action="choose"][data-repository="gardener/GardenA"]').click();
  await page.locator('#github-local-folder').fill('GardenCopy');
  await page.getByRole('button',{name:'Download & open project',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Engineering, connected.',exact:true})).toBeVisible();
  assert.equal((await snapshot()).root,path.join(projectsFolder,'GardenCopy'));
  assert.equal((await snapshot()).artifacts.length,0,'Only approved main was uploaded and downloaded');
  await open(b);await githubSetup();
  await page.getByRole('button',{name:'Choose existing repository',exact:true}).click();
  await page.locator('[data-project-action="choose"][data-repository="gardener/ExistingGarden"]').click();
  await page.getByRole('button',{name:'Connect repository',exact:true}).click();
  await expect(page.locator('.modal')).toContainText('separate histories');
  await page.getByRole('button',{name:'Back to GitHub setup',exact:true}).click();
  await page.getByRole('button',{name:'Choose existing repository',exact:true}).click();
  await page.locator('[data-project-action="choose"][data-repository="gardener/EmptyGarden"]').click();
  await page.getByRole('button',{name:'Connect and upload',exact:true}).click();
  await expect(page.locator('.modal-head h2')).toHaveText('Project connected to GitHub');
  await page.keyboard.press('Escape');await projects();
  // Register an existing folder without moving it, then forget another without deleting it.
  await page.getByRole('button',{name:'Open local folder',exact:true}).click();
  await page.locator('#project-path').fill(path.join(temp,'ExistingGarden'));
  await page.locator('.modal').getByRole('button',{name:'Open project',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Engineering, connected.',exact:true})).toBeVisible();
  assert.equal((await snapshot()).root,path.join(temp,'ExistingGarden'));
  await projects();await page.locator(`[data-project-action="forget"][data-id="${b}"]`).click();
  await expect(page.locator(`[data-project-action="open"][data-id="${b}"]`)).toHaveCount(0);
  assert.ok(fs.existsSync(path.join(projectsFolder,'GardenB/ekf.yaml')));
  await page.screenshot({path:'/tmp/ekf-projects.png',fullPage:true,animations:'disabled'});
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.locator('body').evaluate(el=>el.scrollWidth>innerWidth),false);
  await page.screenshot({path:'/tmp/ekf-projects-mobile.png',fullPage:true,animations:'disabled'});
  await agent.dispose();
  console.log('Empty start, local creation/opening, project isolation, stale tabs, scoped agent access, GitHub sign-in UI, explicit visibility, publication, clone, existing connections and mobile layout passed. GitHub API/account simulated; Git transfers are real.');
};
