const { expect } = require(process.env.EKF_PLAYWRIGHT || '@playwright/test');
const assert = require('node:assert/strict');

module.exports = async function checkGraphRoot({page,context,base}) {
  const snapshot=await (await context.request.get(base+'/api/snapshot')).json();
  await page.locator('.nav-item[data-page="overview"]').click();
  const panel=page.locator('.overview-graph-panel'),select=page.getByLabel('Overview graph root',{exact:true});
  const type=page.getByLabel('Overview root type',{exact:true});
  await expect(type).toHaveValue('');
  await expect(select.locator('option')).toHaveCount(snapshot.artifacts.length);
  const component=snapshot.artifacts.find(a=>a.type==='component');
  await type.selectOption('component');
  assert.deepEqual(await select.locator('option').evaluateAll(els=>els.map(el=>el.value)),snapshot.artifacts.filter(a=>a.type==='component').map(a=>a.id).sort());
  await select.selectOption(component.id);
  await expect(panel.locator('.graph-node.is-root')).toHaveAttribute('data-artifact',component.id);
  const rootX=await panel.locator('.is-root>rect').first().getAttribute('x');
  const otherXs=await panel.locator('.graph-node:not(.is-root)>rect:first-child').evaluateAll(els=>els.map(el=>Number(el.getAttribute('x'))));
  assert.ok(otherXs.every(x=>x>Number(rootX)),'Selected component must be the leftmost node');
  assert.ok(await panel.locator('.graph-node').count()<=10,'Mini graph must remain bounded');
  await page.locator('.nav-item[data-page="knowledge"]').click();
  await page.locator('.nav-item[data-page="overview"]').click();
  await expect(select).toHaveValue(component.id);
  await page.reload();
  await expect(type).toHaveValue('component');
  await expect(select).toHaveValue(component.id);

  await type.selectOption('');
  await expect(select).toHaveValue(component.id);
  await expect(select.locator('option')).toHaveCount(snapshot.artifacts.length);
  await type.selectOption('evidence');

  await select.selectOption('EVID-SAFE-042');
  await expect(panel.locator('.graph-node.is-root')).toHaveAttribute('data-artifact','EVID-SAFE-042');
  await expect(panel.locator('.graph-node[data-artifact="VER-SAFE-001"]')).toBeVisible();
  const edge=panel.locator('.graph-edge[data-source="VER-SAFE-001"][data-target="EVID-SAFE-042"]');
  await panel.locator('.graph-node.is-root').hover();
  await expect(edge).toHaveClass(/is-incoming/);
  await panel.getByRole('button',{name:'Zoom in',exact:true}).click();
  await expect(panel.locator('.graph-zoom-level')).toHaveText('125%');
  await panel.getByRole('button',{name:'Fit',exact:true}).click();
  await panel.locator('.graph-node.is-root').click();
  await expect(page.locator('.drawer')).toContainText('EVID-SAFE-042');
  await page.getByRole('button',{name:'Close artifact',exact:true}).click();
  await panel.getByRole('button',{name:'Explore graph',exact:true}).click();
  await expect(page.locator('#graph-focus')).toHaveValue('EVID-SAFE-042');
  await expect(page.locator('.engineering-graph .is-root')).toHaveAttribute('data-artifact','EVID-SAFE-042');
  await expect(page.locator('.graph-node[data-artifact="REQ-MECH-099"]')).toHaveCount(0);

  await page.locator('.nav-item[data-page="overview"]').click();
  await type.selectOption('manufacturing-requirement');
  await expect(select.locator('option')).toHaveCount(1);
  await select.selectOption('REQ-MECH-099');
  await expect(panel.locator('.graph-node')).toHaveCount(1);
  await expect(panel.locator('.overview-graph-count')).toHaveText('No linked artifacts in this version.');
  await page.getByLabel('Workspace version',{exact:true}).selectOption('example-v0.1');
  await expect(type).toHaveValue('');
  await expect(select).not.toHaveValue('REQ-MECH-099');
  await expect(select.locator('option[value="REQ-MECH-099"]')).toHaveCount(0);
  await select.selectOption('REQ-SAFE-001');
  await expect(panel.locator('.is-root')).toHaveAttribute('data-artifact','REQ-SAFE-001');
  await expect(page.locator('.baseline-banner')).toBeVisible();
  await page.getByRole('button',{name:'Return to current workspace',exact:true}).click();
  await expect(select).toHaveValue('REQ-SAFE-001');
  await expect(page.locator('#content')).toHaveCSS('opacity','1');
  await page.screenshot({path:'/tmp/ekf-overview-root.png',fullPage:true,animations:'disabled'});
  await page.setViewportSize({width:390,height:844});
  await type.selectOption('component');
  await select.selectOption(component.id);
  await expect(panel.locator('.is-root')).toHaveAttribute('data-artifact',component.id);
  assert.equal(await page.locator('body').evaluate(el=>el.scrollWidth>innerWidth),false,'Overview root selector causes mobile overflow');
  await page.screenshot({path:'/tmp/ekf-overview-root-mobile.png',fullPage:true,animations:'disabled'});
  await page.setViewportSize({width:1440,height:1100});
  await type.selectOption('');
  await select.selectOption('REQ-SAFE-001');
  await page.locator('.nav-item[data-page="activity"]').click();
  console.log('Overview root selection, persistence, incoming links, graph navigation, isolated roots, baselines and mobile layout passed.');
};
